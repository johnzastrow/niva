"""Convert between `.niva` flows and standalone PyQGIS scripts.

``export_script`` turns a `.niva` flow into a runnable, standalone PyQGIS `.py`:
each algorithm stage becomes a ``processing.run(...)`` call, with the layer piped
from one step into the next and a ``save`` directing the preceding step's OUTPUT to
its destination. This is niva's *eject* path — a non-programmer prototypes in niva,
then exports real PyQGIS to learn from, customise, or hand to a developer.

``import_script`` reverses the export: a script that is a **linear sequence of
``processing.run('alg', {...})`` calls** maps each call back to a ``run`` stage.

ROUND-TRIP IS LIMITED BY DESIGN. niva is a linear pipeline; Python is
Turing-complete. Only niva-generated (or niva-shaped) scripts re-import. Anything
``import_script`` cannot map (loops, conditionals, custom functions, non-processing
API calls, non-literal params) is reported in the returned warnings — never
silently dropped.
"""

from __future__ import annotations

import ast

from .engine.connections import is_connection_ref
from .engine.engine import _scalar
from .grammar import Call, Flow, parse
from .registry import bind, core_registry
from .values import Distance


