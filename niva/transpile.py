# Generated by niva {version} from {source}.
#
# This is a standalone PyQGIS script — run it with QGIS's own Python:
#     <qgis_python> {out_name}
# (or paste the body into the QGIS Python console, which is already initialised).
#
# RE-IMPORT NOTE: `niva import` can read this script back into a .niva flow ONLY
# because niva generated it as a linear sequence of processing.run(...) calls.
# Arbitrary PyQGIS scripts CANNOT be imported — niva is a linear pipeline and
# Python is not. If you edit this file, keep it a flat list of processing.run
# calls for it to remain importable.
# =============================================================================

